        res = set()
        for m in re.finditer(r'\{([a-zA-Z0-9_]+),\s*plural\b', text):
            res.add(m.group(1))
        for m in re.finditer(r'\{([a-zA-Z0-9_]+)\}', text):
            res.add(m.group(1))
        return res

