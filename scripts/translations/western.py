def main():
    datasets = [
        ('de', de_data),
        ('fr', fr_data),
        ('it', it_data),
        ('nl', nl_data),
    ]

    for locale, data in datasets:
        data_keys = get_keys(data)
        missing = EN_KEYS - data_keys
        if missing:
            raise ValueError(f"[{locale}] Missing {len(missing)} keys: {missing}")
        extra = data_keys - EN_KEYS
        if extra:
            raise ValueError(f"[{locale}] Extra {len(extra)} keys: {extra}")

        # Validate placeholders match reference exactly
        for k in EN_KEYS:
            parts = k.split('.')
            ref_val = EN_DATA
            target_val = data
            for p in parts:
                ref_val = ref_val[p]
                target_val = target_val[p]
            ref_phs = extract_placeholders(ref_val)
            target_phs = extract_placeholders(target_val)
            if ref_phs != target_phs:
                raise ValueError(
                    f"[{locale}] Placeholder mismatch in {k}: expected {ref_phs}, got {target_phs}"
                )

    validate_and_save('de', de_data)
    validate_and_save('fr', fr_data)
    validate_and_save('it', it_data)
    validate_and_save('nl', nl_data)

if __name__ == '__main__':
    main()
